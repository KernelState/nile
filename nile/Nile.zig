pub const SeatApi = struct {
    /// Iterate all seats.
    pub fn iter() wl.list.Head(SeatMod, .link).Iterator(.forward) {
        return server.input_manager.seats.iterator(.forward);
    }

    /// Find seat by name.
    pub fn byName(name: []const u8) ?*SeatMod {
        var it = server.input_manager.seats.iterator(.forward);
        while (it.next()) |s| if (std.mem.eql(u8, std.mem.sliceTo(s.wlr_seat.name, 0), name)) return s;
        return null;
    }

    /// Default seat (always exists, name "default").
    pub fn default() *SeatMod {
        return server.input_manager.defaultSeat();
    }

    /// Create a new seat. No-op if name already exists.
    pub fn create(name: [:0]const u8) !void {
        var it = server.input_manager.seats.iterator(.forward);
        while (it.next()) |s| if (std.mem.orderZ(u8, name, s.wlr_seat.name) == .eq) return;
        try SeatMod.create(name);
    }

    /// Destroy a seat by name (cannot destroy "default").
    pub fn destroy(name: []const u8) void {
        if (std.mem.eql(u8, name, "default")) return;
        var it = server.input_manager.seats.iterator(.forward);
        _ = it.next(); // skip default
        while (it.next()) |s| if (std.mem.eql(u8, std.mem.sliceTo(s.wlr_seat.name, 0), name)) {
            s.destroying = true;
            server.wm.dirtyWindowing();
            break;
        };
    }

    /// Focus a window on `seat`.
    pub fn focusWindow(seat: *SeatMod, window: *WindowMod) void {
        seat.wm_requested.focus = .{ .window = window.ref };
        server.wm.dirtyWindowing();
    }

    /// Clear focus on `seat`.
    pub fn clearFocus(seat: *SeatMod) void {
        seat.wm_requested.focus = .clear;
        server.wm.dirtyWindowing();
    }

    /// Focus a shell surface (e.g. layer surface) — rarely needed, use layer API.
    pub fn focusShellSurface(seat: *SeatMod, shell_surface: anytype) void {
        _ = shell_surface;
        _ = seat;
        // Stub: wire to shell surface type when available
        server.wm.dirtyWindowing();
    }

    /// Warp pointer to absolute compositor coordinates.
    pub fn warpPointer(seat: *SeatMod, x: i32, y: i32) void {
        seat.wm_requested.pointer_warp = .{ .x = x, .y = y };
        server.wm.dirtyWindowing();
    }

    /// Start an interactive pointer operation (move). Window manager would then
    /// track pointer motion and call `Window.setPosition` each frame.
    /// Deprecated: use `opStartMove`/`opStartResize` or handle `pointer_button`
    /// events directly. This now starts a move-kind op.
    pub fn opStartPointer(seat: *SeatMod) void {
        startOpImmediate(seat, .move, .{}, null);
    }

    /// Start an interactive move for `window` on `seat`. Compositor should
    /// call this after receiving a `pointer_button` with `kind == .normal`
    /// when it decides the hold should become a move (e.g. Mod+drag).
    pub fn opStartMove(seat: *SeatMod, window: ?*WindowMod) void {
        startOpImmediate(seat, .move, .{}, window);
    }

    /// Start an interactive resize for `window` on `seat`.
    pub fn opStartResize(seat: *SeatMod, window: ?*WindowMod, edges: WindowMod.Edges) void {
        startOpImmediate(seat, .resize, edges, window);
    }

    /// End current seat operation.
    pub fn opEnd(seat: *SeatMod) void {
        // End immediately if op exists, otherwise queue for next manage.
        // Immediate path also clears any pending start_pointer so manageFinish
        // does not recreate the op after we already ended it.
        if (seat.op != null) {
            seat.opEnd();
            seat.wm_requested.op = .none;
        } else {
            // If a start was pending but never committed, cancel it
            switch (seat.wm_requested.op) {
                .start_pointer => seat.wm_requested.op = .none,
                else => seat.wm_requested.op = .end,
            }
            server.wm.dirtyWindowing();
        }
    }

    fn startOpImmediate(seat: *SeatMod, kind: @import("Compositor.zig").PointerButtonKind, edges: WindowMod.Edges, window: ?*WindowMod) void {
        // Create op synchronously so the subsequent pointer_button released
        // sees seat.op != null even if release arrives before next manage
        // (race that previously caused "no move released event").
        if (seat.op == null) {
            const win_x: i32, const win_y: i32, const win_w: u31, const win_h: u31 = if (window) |win|
                .{ win.box.x, win.box.y, @intCast(@max(0, win.box.width)), @intCast(@max(0, win.box.height)) }
            else
                .{ 0, 0, 0, 0 };
            seat.op = .{
                .input = .pointer,
                .start_x = @intFromFloat(seat.cursor.wlr_cursor.x),
                .start_y = @intFromFloat(seat.cursor.wlr_cursor.y),
                .x = @intFromFloat(seat.cursor.wlr_cursor.x),
                .y = @intFromFloat(seat.cursor.wlr_cursor.y),
                .kind = kind,
                .edges = edges,
                .window = if (window) |w| w.ref else null,
                .win_x = win_x,
                .win_y = win_y,
                .win_width = win_w,
                .win_height = win_h,
            };
            seat.cursor.opStartPointer();
        }
        // Also queue via wm_requested for consistency; manageFinish will see op != null and skip duplicate creation
        seat.wm_requested.op = .{ .start_pointer = .{ .kind = kind, .edges = edges, .window = if (window) |w| w.ref else null } };
        server.wm.dirtyWindowing();
    }

    /// Get current pointer position.
    pub fn pointerPos(seat: *SeatMod) struct { x: f64, y: f64 } {
        return .{ .x = seat.cursor.wlr_cursor.x, .y = seat.cursor.wlr_cursor.y };
    }

    /// Set xcursor theme. `name` may be null to use default.
    pub fn setXcursorTheme(seat: *SeatMod, name: ?[*:0]const u8, size: u32) !void {
        try seat.cursor.setTheme(name, size);
    }

    /// Create a key binding on `seat`. Returns the binding handle.
    /// `modifiers` is a bitset of `wlr.Keyboard.ModifierMask` (u32).
    /// `keysym` is an xkbcommon keysym (e.g. `xkb.Keysym.fromName("Return")`).
    pub fn addXkbBinding(seat: *SeatMod, keysym: xkb.Keysym, modifiers: anytype) !*XkbBinding {
        const mods: u32 = switch (@typeInfo(@TypeOf(modifiers))) {
            .int, .comptime_int => @intCast(modifiers),
            else => @bitCast(@as(wlr.Keyboard.ModifierMask, modifiers)),
        };
        const binding = try XkbBinding.create(seat, keysym, mods);
        binding.wm_requested.enabled = true;
        return binding;
    }

    /// Remove all bindings matching keysym+modifiers.
    pub fn removeXkbBinding(seat: *SeatMod, keysym: xkb.Keysym, modifiers: anytype) void {
        const mods: u32 = switch (@typeInfo(@TypeOf(modifiers))) {
            .int, .comptime_int => @intCast(modifiers),
            else => @bitCast(@as(wlr.Keyboard.ModifierMask, modifiers)),
        };
        var it = seat.xkb_bindings.safeIterator(.forward);
        while (it.next()) |binding| {
            if (binding.keysym == keysym and binding.modifiers == mods) {
                binding.destroy();
            }
        }
    }
};

