pub const OutputApi = struct {
    /// Iterate all outputs with a backing `wlr_output`.
    pub fn iter() wl.list.Head(OutputMod, .link).Iterator(.forward) {
        return server.om.outputs.iterator(.forward);
    }

    /// Find output by name (e.g. "DP-1").
    pub fn byName(name: []const u8) ?*OutputMod {
        var it = server.om.outputs.iterator(.forward);
        while (it.next()) |o| {
            if (o.wlr_output) |w| if (std.mem.eql(u8, std.mem.sliceTo(w.name, 0), name)) return o;
        }
        return null;
    }

    /// Primary output = first in list (convenience).
    pub fn primary() ?*OutputMod {
        return server.om.outputs.first();
    }

    /// Set output position in global layout (requires `dirtyWindowing` flush).
    pub fn setPosition(output: *OutputMod, x: i32, y: i32) void {
        output.scheduled.x = x;
        output.scheduled.y = y;
        output.scheduled.auto_layout = false;
        server.wm.dirtyWindowing();
    }

    /// Set scale factor (e.g. 1.0, 1.25, 2.0).
    pub fn setScale(output: *OutputMod, scale: f32) void {
        output.scheduled.scale = @round(scale * 120) / 120;
        server.wm.dirtyWindowing();
    }

    /// Set transform (rotation / flip).
    pub fn setTransform(output: *OutputMod, transform: wl.Output.Transform) void {
        output.scheduled.transform = transform;
        server.wm.dirtyWindowing();
    }

    /// Enable / disable output power (DPMS). True = on.
    pub fn setEnabled(output: *OutputMod, enabled: bool) void {
        output.scheduled.state = if (enabled) .enabled else .disabled_hard;
        server.wm.dirtyWindowing();
    }

    /// Whether tearing (async page flip) is allowed on this output.
    pub fn setTearing(output: *OutputMod, tearing: bool) void {
        output.rendering_requested.tearing = tearing;
        server.wm.dirtyRendering();
    }

    /// Re-run automatic layout for outputs marked `auto_layout`.
    pub fn autoLayout() void {
        server.om.autoLayout();
        server.wm.dirtyWindowing();
    }

    /// Read current (committed) output box in global coords.
    pub fn currentBox(output: *OutputMod) wlr.Box {
        return output.current.box();
    }

    /// Effective box — prefers `current` but falls back to `sent`/`scheduled`
    /// when the output hasn't committed its initial modeset yet (width/height == 0).
    /// Useful for early window placement before the first `commitOutputState`.
    pub fn effectiveBox(output: *OutputMod) wlr.Box {
        const cur = output.current.box();
        if (cur.width != 0 and cur.height != 0) return cur;
        const sent = output.sent.box();
        if (sent.width != 0 and sent.height != 0) return sent;
        return output.scheduled.box();
    }
};

