/// If true, re-advertise the legacy `river_*_v1` globals for compatibility
/// with old external window managers. Default `false` - Nile is function-only.
pub var enableLegacyProtocols: bool = false;

/// Request that the compositor re-evaluates windowing state on the next idle.
/// Equivalent to the old `river_window_manager_v1.manage_dirty` request, but
/// as a plain function. Safe to call from any thread that holds the Wayland
/// event loop lock (i.e. the main thread).
pub fn dirtyWindowing() void {
    server.wm.dirtyWindowing();
}

/// Lazy variant - schedules a manage sequence without blocking input.
/// Mirrors `dirtyWindowingLazy`.
pub fn dirtyWindowingLazy() void {
    server.wm.dirtyWindowingLazy();
}

/// Mark rendering state dirty (position, stacking order, borders, clip boxes).
pub fn dirtyRendering() void {
    server.wm.dirtyRendering();
}

/// Immediate variant — apply pending rendering state to the scene graph
/// synchronously without waiting for the next idle. Use from
/// `onPointerMotion` for move/drag to achieve per-wayland-call latency.
/// Only rendering state is flushed; windowing (dimensions/configure) still
/// goes through `dirtyWindowing`/`dirtyWindowingLazy`.
pub fn dirtyRenderingImmediate() void {
    server.wm.dirtyRenderingImmediate();
}

/// Animation controls — see `Animation.zig` for kinds, durations and JSON.
/// Example: `Nile.setAnimationConfig(Animation.Config.disabled())` to disable all.
pub fn setAnimationConfig(config: Animation.Config) void {
    Animation.set(config);
}
pub fn getAnimationConfig() Animation.Config {
    return Animation.get();
}
pub fn disableAllAnimations() void {
    Animation.disableAll();
}
/// Load animation config from JSON file (e.g. `~/.config/nile/animations.json`).
/// Missing file → keep defaults. Unknown fields are ignored for forward compat.
pub fn loadAnimationConfigFromFile(path: []const u8) !void {
    const cfg = try Animation.Config.loadFromFile(std.heap.page_allocator, path);
    Animation.set(cfg);
}
/// Load from XDG config home (`$XDG_CONFIG_HOME/nile/animations.json` or `~/.config/nile/animations.json`).
pub fn loadAnimationConfigFromXdg() void {
    _ = Animation.loadGlobalFromXdg(std.heap.page_allocator);
}

/// Terminate the Wayland session. Equivalent to `river_window_manager_v1.exit_session`.
pub fn exitSession() void {
    server.wl_server.terminate();
}

/// The struct that controls all compositor behavior. See `Compositor.zig`.
/// Register your implementation before the first window appears:
/// `Nile.setCompositor(Compositor.initCompositor(MyCompositor, &my_instance))`
pub fn setCompositor(compositor: Compositor.Compositor) void {
    Compositor.set(compositor);
}

pub fn clearCompositor() void {
    Compositor.clear();
}

pub const Event = Compositor.Event;

// ---------------------------------------------------------------------------
// Window API — replaces `river_window_v1`
// ---------------------------------------------------------------------------

pub const WindowApi = struct {
    /// Return a slice of all currently known windows (including unmapped).
    /// The slice is valid until the next window create/destroy.
    /// Caller must not free the slice; iterate directly via `server.wm.windows`.
    pub fn count() usize {
        var n: usize = 0;
        var it = server.wm.windows.iterator();
        while (it.next()) |_| n += 1;
        return n;
    }

    /// Iterate windows. Example:
    /// ```zig
    /// var it = Nile.Window.iter();
    /// while (it.next()) |win| { ... }
    /// ```
    pub fn iter() @import("slotmap").SlotMap(*WindowMod).Iterator {
        return server.wm.windows.iterator();
    }

    /// Get window by its stable `Ref` (survives across transactions).
    pub fn get(ref: WindowMod.Ref) ?*WindowMod {
        return ref.get();
    }

    /// Close the window. The client may ignore the request (e.g. show a save dialog).
    /// Always succeeds from the compositor side; the actual destruction is async.
    pub fn close(window: *WindowMod) void {
        window.wm_requested.close = true;
        server.wm.dirtyWindowing();
    }

    /// Propose new content dimensions for the window.
    /// `width`/`height` of 0 means "let the client choose".
    /// This mutates `wm_requested.dimensions` and dirties windowing state.
    /// `animate` true means visual size change is interpolated (200ms) at
    /// river layer; false means immediate. Grabbed windows are always immediate
    /// regardless of flag to avoid input lag.
    pub fn setDimensions(window: *WindowMod, width: u31, height: u31, animate: bool) void {
        window.wm_requested.dimensions = .{ .width = width, .height = height };
        // Visual size animation — batch with position if also animating same frame
        if (animate and window.state == .mapped) {
            window.startSizeAnimation(@intCast(width), @intCast(height), true);
        } else {
            window.startSizeAnimation(@intCast(width), @intCast(height), false);
        }
        server.wm.dirtyWindowing();
    }

    /// Convenience: set width/height with i32 args (negative values rejected).
    pub fn setDimensionsChecked(window: *WindowMod, width: i32, height: i32, animate: bool) error{InvalidDimensions}!void {
        if (width < 0 or height < 0) return error.InvalidDimensions;
        window.wm_requested.dimensions = .{ .width = @intCast(width), .height = @intCast(height) };
        if (animate and window.state == .mapped) {
            window.startSizeAnimation(width, height, true);
        } else {
            window.startSizeAnimation(width, height, false);
        }
        server.wm.dirtyWindowing();
    }

    /// Backwards-compat wrapper without animation flag (defaults to animate=true).
    pub fn setDimensionsNoAnim(window: *WindowMod, width: u31, height: u31) void {
        setDimensions(window, width, height, true);
    }

    /// Set the window's position in global compositor space (rendering state).
    /// `animate` true interpolates at river layer (200ms easeOutCubic), false
    /// applies immediately. Grabbed windows (seat.op.window) are forced immediate
    /// even if animate=true to prevent cursor lag. Batched: rapid pos+size changes
    /// in same arrange are coalesced into one animation from current visual to
    /// final target.
    pub fn setPosition(window: *WindowMod, x: i32, y: i32, animate: bool) void {
        window.rendering_requested.x = x;
        window.rendering_requested.y = y;
        if (animate) {
            window.startPosAnimation(x, y, true);
            // Animation drives visual; still need to ensure frame is scheduled.
            // Timer will tick, but also mark rendering dirty for final commit.
            server.wm.dirtyRendering();
        } else {
            window.startPosAnimation(x, y, false);
            server.wm.dirtyRendering();
        }
    }

    /// Immediate variant — update scene graph synchronously without waiting
    /// for idle. Use for per-motion drag/move. Still records
    /// `rendering_requested` but also applies `box` + `wlr_scene_tree`
    /// position now, so next frame shows new position without a
    /// `dirtyRendering` idle round-trip. Always animate=false.
    pub fn setPositionImmediate(window: *WindowMod, x: i32, y: i32) void {
        window.rendering_requested.x = x;
        window.rendering_requested.y = y;
        window.startPosAnimation(x, y, false);
        window.applyRenderingImmediate();
        // Clear any pending rendering dirty since we flushed it.
        if (server.wm.rendering_scheduled.dirty) {
            server.wm.cleanRendering();
        }
    }

    /// Hide the window (and its borders/decorations). No-op if already hidden.
    pub fn hide(window: *WindowMod) void {
        window.rendering_requested.hidden = true;
        server.wm.dirtyRendering();
    }

    /// Show a previously hidden window.
    pub fn show(window: *WindowMod) void {
        window.rendering_requested.hidden = false;
        server.wm.dirtyRendering();
    }

    /// Whether the window is currently hidden.
    pub fn isHidden(window: *WindowMod) bool {
        return window.rendering_requested.hidden;
    }

    /// Tell the client to use server-side decoration (SSD) or client-side (CSD).
    pub fn setSsd(window: *WindowMod, ssd: bool) void {
        window.wm_requested.ssd = ssd;
        server.wm.dirtyWindowing();
    }

    /// Inform the window of its tiled edges (affects CSD - e.g. shadows).
    /// `edges` is a bitset of `.top | .bottom | .left | .right` or `.none`.
    pub fn setTiled(window: *WindowMod, edges: anytype) void {
        window.wm_requested.tiled = edges;
        server.wm.dirtyWindowing();
    }

    /// Set which capabilities to advertise to the window (window_menu, maximize, fullscreen, minimize).
    pub fn setCapabilities(window: *WindowMod, caps: WindowMod.Configure) void {
        _ = window;
        _ = caps;
        // Caller can set individual fields via wm_requested.capabilities directly if needed.
        // Provided for symmetry with protocol's set_capabilities.
        server.wm.dirtyWindowing();
    }

    /// Set window borders (rendering state). Pass `edges = .{}` or `width=0` to disable.
    pub fn setBorders(window: *WindowMod, edges: anytype, width: u31, r: u32, g: u32, b: u32, a: u32) void {
        window.rendering_requested.border = .{
            .edges = edges,
            .width = width,
            .r = r,
            .g = g,
            .b = b,
            .a = a,
        };
        server.wm.dirtyRendering();
    }

    /// Clip window + borders + decorations to `box` in window-local coordinates.
    /// Zero width/height disables clipping.
    pub fn setClipBox(window: *WindowMod, clip_box: wlr.Box) void {
        window.rendering_requested.clip = clip_box;
        server.wm.dirtyRendering();
    }

    /// Clip only window content (excluding borders/decorations).
    pub fn setContentClipBox(window: *WindowMod, clip_box: wlr.Box) void {
        window.rendering_requested.content_clip = clip_box;
        server.wm.dirtyRendering();
    }

    /// Make window fullscreen on `output`. Pass null to exit fullscreen.
    pub fn setFullscreen(window: *WindowMod, output: ?*OutputMod) void {
        window.wm_requested.fullscreen = output;
        server.wm.dirtyWindowing();
    }

    /// Convenience: toggle fullscreen.
    pub fn toggleFullscreen(window: *WindowMod, output: *OutputMod) void {
        if (window.wm_requested.fullscreen != null) {
            window.wm_requested.fullscreen = null;
        } else {
            window.wm_requested.fullscreen = output;
        }
        server.wm.dirtyWindowing();
    }

    /// Inform window of fullscreen state for decoration purposes (CSD).
    pub fn setInformFullscreen(window: *WindowMod, fullscreen: bool) void {
        window.wm_requested.inform_fullscreen = fullscreen;
        server.wm.dirtyWindowing();
    }

    /// Inform window it is being interactively resized (affects resize look).
    pub fn setResizing(window: *WindowMod, resizing: bool) void {
        window.wm_requested.resizing = resizing;
        server.wm.dirtyWindowing();
    }

    /// Inform window it is maximized / unmaximized.
    pub fn setMaximized(window: *WindowMod, maximized: bool) void {
        window.wm_requested.maximized = maximized;
        server.wm.dirtyWindowing();
    }

    /// Recommend maximum dimensions to the window (configure_bounds hint).
    pub fn setBounds(window: *WindowMod, max_width: u31, max_height: u31) void {
        window.wm_requested.bounds = .{ .width = max_width, .height = max_height };
        server.wm.dirtyWindowing();
    }

    /// Move window to top of stacking order (last in `rendering_requested` list).
    pub fn raiseToTop(window: *WindowMod) void {
        window.node.link.remove();
        server.wm.rendering_requested.list.append(&window.node);
        server.wm.dirtyRendering();
    }

    /// Focus this window on its seat (uses default seat if none specified).
    pub fn focus(window: *WindowMod) void {
        const seat = server.input_manager.defaultSeat();
        seat.wm_requested.focus = .{ .window = window.ref };
        server.wm.dirtyWindowing();
    }

    /// Accessors for read-only window properties.
    pub fn title(window: *WindowMod) ?[*:0]const u8 {
        return window.getTitle();
    }
    pub fn appId(window: *WindowMod) ?[*:0]const u8 {
        return window.getAppId();
    }
    pub fn box(window: *WindowMod) wlr.Box {
        return window.box;
    }
};

pub const WindowNamespace = WindowApi;

