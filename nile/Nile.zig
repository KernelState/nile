//! Nile ─ Direct, function-based compositor control for River.
//!
//! # Overview
//! Nile replaces River's custom Wayland protocols (`river-window-management-v1`,
//! `river-xkb-bindings-v1`, `river-layer-shell-v1`, `river-input-management-v1`,
//! `river-libinput-config-v1`, `river-xkb-config-v1`) with ordinary Zig functions.
//!
//! Instead of an out-of-process window manager that speaks Wayland, you link
//! Nile as a library (or write a config script that imports it) and manipulate
//! compositor state directly. No `wl_global`, no `manage_start` / `render_finish`
//! dance - just call a function and the compositor applies the change on the
//! next transaction.
//!
//! ## Design principles
//! * **Functions, not protocols.** Every operation that previously required a
//!   `river_*_v1` request is now a Zig function with typed arguments and
//!   `error` returns.
//! * **Synchronous intent, asynchronous commit.** Mutations are recorded
//!   immediately and flushed atomically at the next `commit()` / idle. This
//!   preserves frame perfection of the original transaction system while giving
//!   callers a familiar imperative API.
//! * **No hidden globals.** All state lives in `Server` (`@import("main.zig").server`).
//!   The API is a thin, documented façade over `Window`, `Output`, `Seat`, etc.
//! * **Backwards-compat shim.** The old protocol globals are still generated by
//!   `build.zig` but **not advertised** unless `Nile.enableLegacyProtocols` is
//!   set. New code should not use them.
//!
//! ## Quick start
//! ```zig
//! const Nile = @import("Nile.zig");
//!
//! // Focus a window
//! try Nile.Seat.focusWindow(seat, window);
//!
//! // Tile windows: give each half the output
//! const out = Nile.Output.primary() orelse return;
//! const wins = Nile.Window.list();
//! for (wins, 0..) |w, i| {
//!     const x: i32 = if (i % 2 == 0) out.x else out.x + @divTrunc(out.width, 2);
//!     Nile.Window.setPosition(w, x, out.y);
//!     Nile.Window.setDimensions(w, @divTrunc(out.width, 2), out.height);
//! }
//! Nile.commit();
//! ```
//!
//! See `doc/nile-api.md` for a complete guide.

