pub const Input = struct {
    /// Iterate all input devices.
    pub fn iter() wl.list.Head(InputDevice, .link).Iterator(.forward) {
        return server.input_manager.devices.iterator(.forward);
    }

    /// Find device by name.
    pub fn byName(name: []const u8) ?*InputDevice {
        var it = server.input_manager.devices.iterator(.forward);
        while (it.next()) |d| if (std.mem.eql(u8, std.mem.sliceTo(d.wlr_device.name, 0), name)) return d;
        return null;
    }

    /// Assign device to seat by name. No-op if seat doesn't exist.
    pub fn assignToSeat(device: *InputDevice, seat_name: []const u8) void {
        var it = server.input_manager.seats.iterator(.forward);
        while (it.next()) |s| if (std.mem.eql(u8, std.mem.sliceTo(s.wlr_seat.name, 0), seat_name)) {
            device.assignToSeat(s);
            return;
        };
    }

    /// Set keyboard repeat rate (keys per second) and delay (ms).
    pub fn setRepeat(device: *InputDevice, rate: i32, delay: i32) error{InvalidRate}!void {
        if (rate < 0 or delay < 0) return error.InvalidRate;
        if (device.wlr_device.type != .keyboard) return;
        const kbd: *@import("Keyboard.zig") = @ptrCast(@alignCast(device.wlr_device.data));
        kbd.setRepeatInfo(@intCast(rate), @intCast(delay));
    }

    /// Set scroll factor for pointer devices.
    pub fn setScrollFactor(device: *InputDevice, factor: f64) error{InvalidFactor}!void {
        if (factor < 0) return error.InvalidFactor;
        if (device.wlr_device.type != .pointer) return;
        device.config.scroll_factor = @floatCast(factor);
    }

    /// Map pointer/touch/tablet device to output.
    pub fn mapToOutput(device: *InputDevice, output: ?*wlr.OutputMod) void {
        if (device.wlr_device.type != .pointer and
            device.wlr_device.type != .touch and
            device.wlr_device.type != .tablet) return;
        device.config.map_to_output = output;
        if (device.wlr_device.type == .touch or device.wlr_device.type == .tablet) {
            device.seat.cursor.wlr_cursor.mapInputToOutput(device.wlr_device, output);
        }
    }

    /// Map device to rectangle in global compositor space.
    pub fn mapToRectangle(device: *InputDevice, rect: ?wlr.Box) error{InvalidRectangle}!void {
        if (rect) |r| if (r.width < 0 or r.height < 0) return error.InvalidRectangle;
        if (device.wlr_device.type != .pointer and
            device.wlr_device.type != .touch and
            device.wlr_device.type != .tablet) return;
        if (rect) |r| {
            device.config.map_to_rectangle = r;
            device.config.map_to_output = null;
            if (device.wlr_device.type == .touch or device.wlr_device.type == .tablet) {
                device.seat.cursor.wlr_cursor.mapInputToRegion(device.wlr_device, &r);
            }
        } else {
            device.config.map_to_rectangle = .{ .x = 0, .y = 0, .width = 0, .height = 0 };
            if (device.wlr_device.type == .touch or device.wlr_device.type == .tablet) {
                device.seat.cursor.wlr_cursor.mapInputToRegion(device.wlr_device, null);
            }
        }
    }
};

// ---------------------------------------------------------------------------
// Layer shell API — replaces `river_layer_shell_v1`
// ---------------------------------------------------------------------------

pub const Layer = struct {
    /// Set the default output for new layer surfaces that don't request one.
    pub fn setDefaultOutput(output: *OutputMod) void {
        var it = server.om.outputs.iterator(.forward);
        while (it.next()) |o| o.layer_shell.requested.default = false;
        output.layer_shell.requested.default = true;
        server.wm.dirtyWindowing();
    }

    /// Get non-exclusive area for an output (area left after exclusive zones).
    pub fn nonExclusiveArea(output: *OutputMod) wlr.Box {
        return output.layer_shell.scheduled.non_exclusive_area;
    }
};

